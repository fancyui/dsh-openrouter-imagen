  /**
   * Read local reference images as data URLs.
   *
   * These bytes leave the machine for a third-party API, so a path the *model*
   * chose is confined to the session workspace: `dsh-fs-local` resolves any
   * absolute path and the fs sandbox fences writes, not reads, so without this
   * check the parameter is a read-anything-and-upload-it channel. An unreadable
   * file stays non-fatal, because one bad path should not lose the whole call.
   */
  async function readReferenceFiles(paths, cwd, signal) {
    const fs = ctx.get('fs')
    if (fs === undefined) return []
    const urls = []
    for (const raw of paths.slice(0, MAX_REFERENCES)) {
      if (typeof raw !== 'string' || raw.trim().length === 0) continue
      let target
      try {
        // `fs.resolve` returns a handle { targetKey, displayPath }, NOT a string
        // (dsh-fs-local resolveLocalTarget). `displayPath` is the absolute host
        // path; relative paths must be resolved against the session cwd so a
        // model-supplied bare name behaves like the read/write tools.
        target = await fs.resolve(raw.trim(), typeof cwd === 'string' && cwd.length > 0 ? { cwd } : {})
      } catch (error) {
        console.warn(`[dsh-openrouter-imagen] reference file failed (${raw}): ${errorMessage(error)}`)
        continue
      }
      if (typeof cwd === 'string' && cwd.length > 0) {
        const inside = relative(cwd, String(target.displayPath ?? ''))
        if (inside.startsWith('..') || isAbsolute(inside)) {
          throw new Error(`参考图必须位于会话工作目录内：${raw}（先复制进项目，或用 reference_images 传 http(s)/data URL）`)
        }
      }
      try {
        const bytes = await fs.readBytes(target, signal, 20 * 1024 * 1024)
        if (!bytes || bytes.length === 0) continue
        const lower = raw.toLowerCase()
        const mediaType = lower.endsWith('.jpg') || lower.endsWith('.jpeg') ? 'image/jpeg'
          : lower.endsWith('.webp') ? 'image/webp'
            : lower.endsWith('.gif') ? 'image/gif'
              : 'image/png'
        urls.push(`data:${mediaType};base64,${toBase64(bytes)}`)
      } catch (error) {
        console.warn(`[dsh-openrouter-imagen] reference file failed (${raw}): ${errorMessage(error)}`)
      }
    }
    return urls
  }

