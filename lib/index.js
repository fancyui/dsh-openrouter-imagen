  async function handleApi(req, res) {
    // The same trust fence every shipped route uses: `requestRejection` answers
    // 403 for a foreign Host/Origin and 401 without the browser's auth cookie.
    // Without it any page (or a DNS-rebinding host) could POST to /generate and
    // spend the stored key, or overwrite the settings through /config.
    const connection = ctx.get('connection')
    if (connection !== undefined && typeof connection.requestRejection === 'function') {
      const rejection = connection.requestRejection(req)
      if (rejection !== undefined) {
        sendJson(res, rejection, { ok: false, error: rejection === 401 ? '未通过浏览器鉴权，请从 DSH 窗口访问' : '该来源不被信任' })
        return
      }
    }
    const url = new URL(req.url ?? '/', 'http://127.0.0.1')
    const action = url.pathname.slice(API_PATH.length).replace(/^\/+/, '')
    const method = req.method ?? 'GET'
    try {
      if (action === 'config' && method === 'GET') {
        sendJson(res, 200, { ok: true, ...publicConfig() })
        return
      }
      if (action === 'config' && method === 'POST') {
        const patch = await readJsonBody(req)
        const next = {}
        for (const key of WRITABLE) {
          if (!Object.prototype.hasOwnProperty.call(patch, key)) continue
          if (key === 'apiKey' && String(patch.apiKey ?? '').trim().length === 0) continue
          next[key] = key === 'count' ? Number(patch[key]) : patch[key]
        }
        if (Object.keys(next).length > 0) await scope.update(next)
        sendJson(res, 200, { ok: true, ...publicConfig() })
        return
      }
      if (action === 'models' && method === 'GET') {
        const json = await callApi('/images/models', undefined, { requireKey: false })
        const models = (Array.isArray(json?.data) ? json.data : [])
          .filter((row) => typeof row?.id === 'string' && row.id.length > 0)
          .map((row) => ({ id: row.id, name: typeof row.name === 'string' && row.name.length > 0 ? row.name : row.id }))
          .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
        sendJson(res, 200, { ok: true, models, count: models.length })
        return
      }
      if (action === 'test' && method === 'GET') {
        const json = await callApi('/key')
        const data = json?.data ?? {}
        const parts = []
        if (typeof data.label === 'string' && data.label.length > 0) parts.push(`标签：${data.label}`)
        if (data.is_free_tier === true) parts.push('免费额度账户')
        if (typeof data.usage === 'number') parts.push(`已用：$${data.usage.toFixed(4)}`)
        if (typeof data.limit === 'number') parts.push(`额度上限：$${data.limit.toFixed(2)}`)
        else if (data.limit === null) parts.push('额度上限：未设置（按量付费）')
        if (typeof data.limit_remaining === 'number') parts.push(`剩余：$${data.limit_remaining.toFixed(4)}`)
        sendJson(res, 200, { ok: true, report: parts.length > 0 ? parts.join('　·　') : JSON.stringify(data).slice(0, 300) })
        return
      }
      if (action === 'generate' && method === 'POST') {
        const input = await readJsonBody(req)
        // No `exec` here, so no session workspace: this route is for scripts and
        // the offline pre-flight, and its files stay in the attachment store.
        const result = await generate(input, { withDataUrl: true })
        sendJson(res, 200, {
          ok: true,
          model: result.model,
          prompt: result.prompt,
          referenceCount: result.referenceCount,
          seed: result.seed,
          seedRandom: result.seedRandom,
          params: result.params,
          project: result.project,
          cost: result.cost,
          elapsedMs: result.elapsedMs,
          images: result.images.map((image) => ({
            name: image.name,
            mediaType: image.mediaType,
            bytes: image.bytes,
            filePath: image.filePath,
            dataUrl: image.dataUrl ?? null,
          })),
        })
        return
      }
      // Staged reference images from the composer. GET reports only metadata —
      // the client already holds the bytes it uploaded, and echoing
      // multi-megabyte data URLs back on every poll would be wasteful.
      if (action === 'reference' && method === 'GET') {
        sendJson(res, 200, {
          ok: true,
          count: pendingReferences.length,
          references: pendingReferences.map((url) => {
            const match = /^data:([^;]+);base64,(.*)$/su.exec(url)
            const data = match?.[2] ?? ''
            return { mediaType: match?.[1] ?? 'image/png', bytes: Math.floor((data.length * 3) / 4) }
          }),
        })
        return
      }
      if (action === 'reference' && method === 'POST') {
        const payload = await readJsonBody(req)
        const incoming = Array.isArray(payload?.references) ? payload.references : []
        // Append, not replace: the client can only send the bytes it holds, so
        // a replace protocol would silently drop references staged earlier.
        const next = pendingReferences.slice()
        for (const entry of incoming) {
          if (next.length >= MAX_REFERENCES) break
          if (entry === null || typeof entry !== 'object') continue
          const data = typeof entry.data === 'string' ? entry.data : ''
          const mediaType = MEDIA_EXT[entry.mediaType] === undefined ? null : entry.mediaType
          if (data.length === 0 || mediaType === null) continue
          next.push(`data:${mediaType};base64,${data}`)
        }
        pendingReferences = next
        sendJson(res, 200, { ok: true, count: pendingReferences.length })
        return
      }
      if (action === 'reference' && method === 'DELETE') {
        pendingReferences = []
        sendJson(res, 200, { ok: true, count: 0 })
        return
      }
      sendJson(res, 404, { ok: false, error: `未知接口：${method} ${action}` })
    } catch (error) {
      sendJson(res, 200, { ok: false, error: errorMessage(error) })
    }
  }

  // The API route normally registers here, because the Web carrier is composed
  // long before this row. If it is not up yet, wait for it instead of silently
  // leaving the Settings page calling a 404.
  //
  // The service is reached through ctx.get(), never as `ctx.webServer`: this
  // plugin does not declare webServer in `inject` (declaring it would park the
  // whole plugin — tool included — on any surface without a Web carrier), and
  // an undeclared service read is rejected by the inject guard.
  const registerRoute = (service) => {
    if (service === undefined) return
    ctx.effect(() => service.register({ kind: 'prefix', path: API_PATH, handler: handleApi }), 'openrouter-imagen: api route')
  }

  const webServer = ctx.get('webServer')
  if (webServer !== undefined) registerRoute(webServer)
  else ctx.inject(['webServer'], (webCtx) => registerRoute(webCtx.get('webServer')))
