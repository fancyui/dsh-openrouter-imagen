/**
 * dsh-openrouter-imagen — Host half.
 *
 * Generates images through the OpenRouter Image API (POST /api/v1/images) and
 * exposes them to two consumers:
 *
 *   - the model, through the `openrouter_generate_imagen` tool, whose result
 *     carries durable `image` content blocks;
 *   - the browser, through a same-origin JSON route under
 *     `/openrouter-imagen/api`, which the plugin's Client half calls with
 *     plain `fetch` (no Remote/typert surface is involved).
 *
 * Configuration lives in the `openrouter-imagen` settings namespace, so it
 * persists through the mounted settings provider (settings.yaml) and is
 * editable at runtime from Settings → 图像生成. `apiKey` is declared with
 * `role('secret')`, which keeps it out of every redacted settings protocol
 * response; this module never echoes it back to the browser either.
 *
 * Generated bytes are committed twice on purpose: as a durable attachment (the
 * only thing that makes a picture render in the conversation) and as a verbatim
 * file. The file goes into the calling session's own workspace — `saveDir`
 * under `exec.agent.session.header.cwd` — because that is where the project
 * that asked for it lives; a call with no workspace (or `saveDir` emptied)
 * falls back to the attachment store.
 *
 * Outbound HTTP goes through `undici` with an explicit proxy agent. Node's
 * global `fetch` ignores HTTP_PROXY/HTTPS_PROXY entirely (and the undici
 * package's `setGlobalDispatcher` cannot change that, because globalThis.fetch
 * runs on Node's internal copy of undici), so on a machine whose only route
 * out is a local proxy the global fetch silently takes a different network.
 * The resolution order below mirrors `dshmarket/lib/net.js`.
 *
 * @module dsh-openrouter-imagen
 */
