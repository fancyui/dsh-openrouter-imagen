const NS = 'openrouter-imagen'
/**
 * API root. Overridable so a deployment can point at a gateway or a local
 * stand-in, and so the offline pre-flight can assert the exact request body
 * against a mock server instead of a live account.
 */
const API_BASE = (process.env.OPENROUTER_IMAGE_API_BASE ?? '').trim() || 'https://openrouter.ai/api/v1'
const API_PATH = '/openrouter-imagen/api'
const MEDIA_EXT = { 'image/png': '.png', 'image/jpeg': '.jpg', 'image/webp': '.webp', 'image/gif': '.gif' }
